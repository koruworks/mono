/// Every foundation record, in the order the navigator lists them.
pub(super) const RECORDS: &[Entry] = &{
    let mut all = [TOKEN_RECORDS[0]; 58];
    let mut at = 0;
    let groups: [&[Entry]; 4] = [
        &TOKEN_RECORDS,
        &THEME_RECORDS,
        &ELEMENT_RECORDS,
        &DRAWING_RECORDS,
    ];
    let mut group = 0;
    while group < groups.len() {
        let mut i = 0;
        while i < groups[group].len() {
            all[at] = groups[group][i];
            at += 1;
            i += 1;
        }
        group += 1;
    }
    assert!(at == all.len(), "the foundation count is every group's");
    all
};
