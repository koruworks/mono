const SCENE: &str = "crates/koru-draw/src/scene.rs";

/// The family the component catalog files `koru-draw`'s drawing primitives,
/// theme, text, geometry and animation under.
const P_DRAW: Option<&str> = Some("P-DRAW");

const fn draw(module: &'static str, file: &'static str) -> Source {
    Source {
        owner: "koru-draw",
        module,
        file,
    }
}

/// The element layer: shared desktop Rust whose mobile adapters are planned
/// as the element contract's fourth rung, not built.
const ELEMENT_LAYER: [(Platform, Availability); 5] = [
    (Platform::Windows, Availability::Existing),
    (Platform::MacOs, Availability::SharedSourceUnverified),
    (Platform::Linux, Availability::SharedSourceUnverified),
    (Platform::Android, Availability::Planned),
    (Platform::Ios, Availability::Planned),
];

#[allow(clippy::too_many_arguments)]
const fn record(
    catalog_id: &'static str,
    public_name: &'static str,
    name: Key,
    purpose: Key,
    kind: Kind,
    catalog_family: Option<&'static str>,
    source: Source,
    platforms: [(Platform, Availability); 5],
    apis: &'static [Api],
) -> Entry {
    Entry {
        catalog_id,
        public_name,
        name,
        purpose,
        family: Family::Foundations,
        kind,
        catalog_family,
        identities: &[],
        source,
        platforms,
        recipes: &[],
        apis,
    }
}

