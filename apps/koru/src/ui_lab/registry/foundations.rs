//! **Foundations**: `koru-draw`'s tokens and themes, the element layer, the
//! drawing primitives below the component level, and the support code they
//! share. Each record was written from the module it names;
//! `registry/MANIFEST.md` lists what was read.
//!
//! Token tables list their members as the source spells them and carry no
//! translated labels: `S4` is `S4` in every language. Where the composition
//! catalog lets a declaration name a token, [`A2ui::Values`] pairs each
//! declared value with the member it resolves to.

use super::*;
use koru_i18n::Key;

