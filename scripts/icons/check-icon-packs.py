"""Check every pack and return to Tabler against a scoped artifact baseline.

Runs real Rust compilation and checks license/ICO/PNG content at each step.
Restores the caller's original generated artifacts even on failure. It never
resets Git or touches unrelated source changes.
"""
import subprocess
import sys

from PIL import Image
from icon_pack import ROOT, PACKS, SELECTABLE_PACKS, bundled_notice, catalog_notices, load_icons, rust_catalog

SUFFIXES = ("", "-beta", "-nightly", "-internal-debug", "-internal-release")
IMAGES = [ROOT / "assets/document.ico"] + [
    ROOT / f"assets/koru-ai-chat{suffix}.{ext}" for suffix in SUFFIXES for ext in ("ico", "png")]
ARTIFACTS = [ROOT / "crates/koru-draw/src/icon_pack_data.rs"] + [
    ROOT / f"crates/koru-release/licences/bundled/icons-{pack}.txt" for pack in PACKS] + IMAGES
SIZES = {(size, size) for size in (16, 24, 32, 48, 64, 128, 256)}


def snapshot():
    return {path: path.read_bytes() if path.exists() else None for path in ARTIFACTS}


def verify(pack):
    icons, notices = load_icons(pack)
    assert ARTIFACTS[0].read_text(encoding="utf-8") == rust_catalog(pack, 1.85)
    notices = catalog_notices()
    for name, notice in notices.items():
        path = ROOT / f"crates/koru-release/licences/bundled/icons-{name}.txt"
        assert path.read_text(encoding="utf-8") == bundled_notice(name, notice), path
    for path in IMAGES:
        with Image.open(path) as image:
            if path.suffix == ".ico":
                assert image.ico.sizes() == SIZES, path
                for size in SIZES:
                    assert image.ico.getimage(size).convert("RGBA").getbbox(), (path, size)
            else:
                image.load()
                assert image.size == (256, 256) and image.getbbox(), path
    cargo = ["cargo", "test", "--manifest-path", str(ROOT / "Cargo.toml")]
    subprocess.run(cargo + ["-p", "koru-draw"], check=True, cwd=ROOT)
    subprocess.run(cargo + ["-p", "koru", "popover_baseline::the_"], check=True, cwd=ROOT)


def main():
    original = snapshot()
    baseline = None
    try:
        for pack in ("tabler", *(p for p in SELECTABLE_PACKS if p != "tabler"), "tabler"):
            subprocess.run([sys.executable, str(ROOT / "scripts/icons/sync-icon-pack.py"), "--pack", pack], check=True)
            verify(pack)
            actual = snapshot()
            if baseline is None:
                baseline = actual
            elif pack == "tabler":
                differences = [str(path.relative_to(ROOT)) for path in ARTIFACTS if baseline[path] != actual[path]]
                if differences:
                    raise ValueError(f"pack round trip changed generated bytes: {differences}")
            else:
                for path in [ARTIFACTS[0], *IMAGES]:
                    assert baseline[path] != actual[path], f"pack selection did not update {path}"
        print(f"Pack round trip passed: {len(ARTIFACTS)} artifacts restored byte-for-byte")
    finally:
        for path, data in original.items():
            if data is None:
                path.unlink(missing_ok=True)
            else:
                path.write_bytes(data)


if __name__ == "__main__":
    main()
