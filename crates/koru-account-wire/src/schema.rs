macro_rules! define_catalogue {
    ($($type:ty),+ $(,)?) => {
        pub const TYPE_NAMES: &[&str] = &[$(stringify!($type)),+];

        pub fn catalogue() -> BTreeMap<&'static str, Schema> {
            let mut schemas = BTreeMap::new();
            $(schemas.insert(stringify!($type), schemars::schema_for!($type));)+
            schemas
        }
    };
}

